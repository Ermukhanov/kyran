class DemoSource:
    name = "demo"

    @property
    def enabled(self) -> bool:
        return config.DEMO_MODE

    async def fetch(self) -> list[LotData]:
        if not self.enabled:
            return []
        now = datetime.now(config.TZ).replace(minute=0, second=0, microsecond=0)
        day = now.strftime("%Y%m%d")
        lots = []
        for i, (title, desc, customer, amount, region, method, days) in enumerate(DEMO, 1):
            lots.append(LotData(
                source="demo", ext_id=f"{day}-{i}", title=title, description=desc, customer=customer,
                amount=float(amount), region=region, method=method,
                deadline=(now + timedelta(days=days)).replace(hour=18),
                published_at=now - timedelta(hours=i), url="", is_demo=True,
            ))
        return lots
